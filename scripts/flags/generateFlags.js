import * as glob from 'glob'
import { promises as fs } from 'fs'
import { chromium } from 'playwright'

// Flags are pre-rendered to small WebP images instead of embedding the raw SVGs: some SVG flags
// weigh up to 250 KB (coats of arms) while they are displayed at ~16px high.
// Rendered at this height, they stay sharp up to 24px on high-density (2x) screens and weigh 1-2 KB.
const RENDER_HEIGHT = 48
const WEBP_QUALITY = 0.9

const OUTPUT_PATH = './src/components/CountryFlag/flagSources.ts'

const getFlagCodeFromFlagPath = svgFlagPath => /([^/]+)\.svg$/.exec(svgFlagPath)[1]

// Flags are not all 3:2 (from 1:1 to ~2.5:1): read the intrinsic ratio so they are never squashed.
const getSvgAspectRatio = svgFlagSource => {
  const svgTag = /<svg[^>]*>/.exec(svgFlagSource)[0]
  const width = Number(/\swidth="([\d.]+)"/.exec(svgTag)?.[1])
  const height = Number(/\sheight="([\d.]+)"/.exec(svgTag)?.[1])
  if (width && height) {
    return width / height
  }

  const [, , viewBoxWidth, viewBoxHeight] = /\sviewBox="([^"]+)"/.exec(svgTag)[1].trim().split(/[\s,]+/).map(Number)

  return viewBoxWidth / viewBoxHeight
}

// Rasterize the SVG in Chromium and encode it to WebP via a canvas (Playwright screenshots can't output WebP).
const renderSvgToWebpDataUrl = (page, { height, svgFlagSource, width }) =>
  page.evaluate(
    async ({ height, quality, svgDataUrl, width }) => {
      const image = new Image()
      image.src = svgDataUrl
      await image.decode()

      const canvas = document.createElement('canvas')
      canvas.width = width
      canvas.height = height
      canvas.getContext('2d').drawImage(image, 0, 0, width, height)

      return canvas.toDataURL('image/webp', quality)
    },
    {
      height,
      quality: WEBP_QUALITY,
      svgDataUrl: `data:image/svg+xml;base64,${Buffer.from(svgFlagSource).toString('base64')}`,
      width
    }
  )

// Chromium embeds a ~460 B sRGB ICC profile in every WebP, often more than the image itself.
// Browsers assume sRGB anyway, so drop the `ICCP` chunk and unset its flag in the `VP8X` header.
const stripWebpIccProfile = webpDataUrl => {
  const webp = Buffer.from(webpDataUrl.split(',')[1], 'base64')
  const chunks = []
  let offset = 12 // Skip the `RIFF` + size + `WEBP` header
  while (offset < webp.length) {
    const chunkSize = 8 + webp.readUInt32LE(offset + 4)
    const chunk = Buffer.from(webp.subarray(offset, offset + chunkSize + (chunkSize % 2)))
    const chunkType = chunk.toString('ascii', 0, 4)
    if (chunkType === 'VP8X') {
      chunk[8] &= ~0x20 // ICC profile flag
    }
    if (chunkType !== 'ICCP') {
      chunks.push(chunk)
    }

    offset += chunk.length
  }

  const body = Buffer.concat([Buffer.from('WEBP', 'ascii'), ...chunks])
  const header = Buffer.alloc(8)
  header.write('RIFF', 0, 'ascii')
  header.writeUInt32LE(body.length, 4)

  return `data:image/webp;base64,${Buffer.concat([header, body]).toString('base64')}`
}

async function generateFlagSource({ count, index, page, svgFlagPath }) {
  const flagCode = getFlagCodeFromFlagPath(svgFlagPath)
  console.log(`Generating flags: [${index + 1}/${count}] Rendering ${flagCode}.svg…`)

  const svgFlagSource = (await fs.readFile(svgFlagPath, 'utf-8')).trim()
  const width = Math.round(RENDER_HEIGHT * getSvgAspectRatio(svgFlagSource))
  const webpDataUrl = await renderSvgToWebpDataUrl(page, { height: RENDER_HEIGHT, svgFlagSource, width })
  if (!webpDataUrl.startsWith('data:image/webp')) {
    throw new Error(`Generating flags: ${flagCode}.svg could not be encoded to WebP.`)
  }

  return [flagCode, stripWebpIccProfile(webpDataUrl)]
}

console.log('Generating flags: Fetching files…')

const svgFlagPaths = glob.sync('./scripts/flags/*.svg').sort()
const count = svgFlagPaths.length
const flagSources = []
let index = -1

const browser = await chromium.launch()
const page = await browser.newPage()

while (++index < count) {
  flagSources.push(await generateFlagSource({ count, index, page, svgFlagPath: svgFlagPaths[index] }))
}

await browser.close()

console.log(`Generating flags: Writing ${OUTPUT_PATH}…`)

const tsFlagSourcesSource = [
  '// Generated by `yarn flags` (`scripts/flags/generateFlags.js`): do not edit manually.',
  '',
  '/** WebP data URLs of country flags, keyed by ISO 3166-1 alpha-3 code (e.g. `FRA`). */',
  'export const FLAG_SOURCES: Record<string, string> = {',
  flagSources.map(([flagCode, dataUrl]) => `  ${JSON.stringify(flagCode)}: ${JSON.stringify(dataUrl)}`).join(',\n'),
  '}',
  ''
].join('\n')

await fs.writeFile(OUTPUT_PATH, tsFlagSourcesSource, 'utf-8')

console.log('Flags generated.')

